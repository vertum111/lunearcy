const ENTRIES=Object.entries(D).sort((a,b)=>b[0].length-a[0].length).map(([k,v])=>{
 const esc=k.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
 // short words only match whole words so they never chew into longer untranslated words
 return [k.length<=6?new RegExp(`(?<![\\p{L}’'])${esc}(?![\\p{L}’'])`,'gu'):new RegExp(esc,'g'),v];
});
const CYR=/[А-Яа-яЄєІіЇїҐґ]/;
const cache=new Map();
export function tr(text){
 if(lang==='uk'||!text||!CYR.test(text))return text;
 if(cache.has(text))return cache.get(text);
 let out=text;
 for(const[re,v]of PATTERNS)out=out.replace(re,v);
 for(const[re,v]of ENTRIES){if(!CYR.test(out))break;out=out.replace(re,v);}
 if(cache.size>4000)cache.clear();cache.set(text,out);return out;
}
const ATTRS=['aria-label','title','placeholder','alt'];
export function translateNode(root){
 if(root.nodeType===3){if(root.parentElement?.closest('[data-no-tr]'))return;const t=tr(root.data);if(t!==root.data)root.data=t;return;}
 if(root.nodeType!==1)return;
 for(const a of ATTRS){const v=root.getAttribute?.(a);if(v&&CYR.test(v)){const t=tr(v);if(t!==v)root.setAttribute(a,t);}}
 const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT|NodeFilter.SHOW_ELEMENT);
 for(let n=walker.nextNode();n;n=walker.nextNode()){
  if(n.nodeType===3){if(CYR.test(n.data)&&!n.parentElement?.closest('[data-no-tr]')){const t=tr(n.data);if(t!==n.data)n.data=t;}}
  else for(const a of ATTRS){const v=n.getAttribute(a);if(v&&CYR.test(v)){const t=tr(v);if(t!==v)n.setAttribute(a,t);}}
 }
}
export function startI18n(){
 document.documentElement.lang=lang;
 if(lang==='uk')return;
 document.title=tr(document.title);
 translateNode(document.body);
 new MutationObserver(list=>{for(const m of list){if(m.type==='characterData')translateNode(m.target);else if(m.type==='attributes')translateNode(m.target);else for(const n of m.addedNodes)translateNode(n);}}).observe(document.body,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:ATTRS});
}
